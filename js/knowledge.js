// 지식 검색 — 카테고리 감지 + 스코어링 (나중에 임베딩으로 교체 가능)
function searchKnowledge(text) {
  const t = (text || "").replace(/\s/g, "");

  // 1) 업무방법(howto)을 먼저 — "카드 잃어버렸어"는 상품추천이 아니라 재발급 안내
  const howto = IM_KNOWLEDGE.howto.filter(h => h.q.some(k => t.includes(k)));

  // 2) 질문이 어느 카테고리를 겨냥하는지 감지
  const catHint =
    /(적금|저축|모으)/.test(t) ? "적금" :
    /(예금|통장|청약|연금)/.test(t) ? "예금" :
    /(대출|빌리|전세|전월세|월세|담보)/.test(t) ? "대출" :
    /(카드)/.test(t) ? "카드" :
    /(환전|외환|달러|여행|해외)/.test(t) ? "외환" : null;

  // 3) 스코어링: 카테고리 일치 +3, 태그 일치 +1, 상품명 일치 +5
  const scored = IM_KNOWLEDGE.products.map(p => {
    let s = 0;
    if (catHint && p.cat === catHint) s += 3;
    s += p.tags.filter(tag => t.includes(tag)).length;
    if (t.includes(p.name.replace(/\s/g, ""))) s += 5;
    return { p, s };
  }).filter(x => x.s > 0).sort((a, b) => b.s - a.s);

  // 상품/추천 의도가 명시적인지 (이 신호가 없으면 howto 우선)
  const wantsProduct = /(추천|가입|상품|뭐가좋|뭐있|알아보|들고싶|만들|개설)/.test(t);
  // howto가 걸렸으면 우선 (분실·재발급·인증서 등은 절차안내)
  //   단, 상품명 직접언급(+5) 또는 명시적 상품의도가 있으면 상품 우선
  if (howto.length && !(scored[0]?.s >= 5) && !wantsProduct) {
    return { products: [], howto };
  }
  return { products: scored.map(x => x.p), howto };
}
